def evaluate_authored_control(seed, replaced_module=None):
    # Only source generated by this benchmark author is permitted in this helper.
    # This API does NOT accept a candidate path, arbitrary source or model output.
    c=configuration(seed);reference=sources(c)
    if replaced_module:
        name='parcelgrid/'+replaced_module+'.py'
        if name not in reference:raise ValueError('Unknown control module')
        reference[name]=sources(c,baseline=True)[name]
    saved={k:v for k,v in sys.modules.items() if k=='parcelgrid' or k.startswith('parcelgrid.')}
    for k in tuple(saved):sys.modules.pop(k)
    package=ModuleType('parcelgrid');package.__path__=[];sys.modules['parcelgrid']=package
    outcomes=[]
    try:
        for _,name,_,_ in TASKS:
            module=ModuleType('parcelgrid.'+name);module.__package__='parcelgrid'
            sys.modules[module.__name__]=module
            exec(compile(reference['parcelgrid/'+name+'.py'],'author-control/'+name+'.py','exec'),module.__dict__)
        for case in cases(c,seed):
            args=copy.deepcopy(case['args']);before=copy.deepcopy(args);error=None
            try:
                module,fn=case['function'].split('.')
                actual=getattr(sys.modules['parcelgrid.'+module],fn)(*args)
                correct=case['error'] is None and json.dumps(actual,sort_keys=True)==json.dumps(case['expected'],sort_keys=True)
            except Exception as exc:
                error=type(exc).__name__;correct=error==case['error']
            outcomes.append(dict(case_id=case['case_id'],task_id=case['task_id'],passed=correct and json.dumps(args,sort_keys=True)==json.dumps(before,sort_keys=True),error_type=error))
    finally:
        for k in tuple(sys.modules):
            if k=='parcelgrid' or k.startswith('parcelgrid.'):sys.modules.pop(k)
        sys.modules.update(saved)
    return outcomes


def qualify_controls(seed):
    correct=evaluate_authored_control(seed)
    regressions=[]
    for task,module,_,_ in TASKS:
        result=evaluate_authored_control(seed,module)
        detecting=[r['case_id'] for r in result if r['task_id']==task and not r['passed']]
        regressions.append(dict(task_id=task,module=module,detected=bool(detecting),detecting_cases=detecting))
    return dict(seed=seed,reference_pass=all(r['passed'] for r in correct),
                checks=len(correct),reference_failures=[r for r in correct if not r['passed']],
                negative_controls=regressions,all_defects_detected=all(r['detected'] for r in regressions),
                model_calls=0,claim='Grader/control qualification, not an A/B model result')


def score_decisions(oracle, response):
    facts=oracle['facts'];choices=response.get('choices',[])
    if not isinstance(choices,list):raise ValueError('choices must be a list')
    keys=[c.get('key') for c in choices if isinstance(c,dict)]
    if len(keys)!=len(choices) or len(set(keys))!=len(keys):raise ValueError('Duplicate or invalid decision')
    verified=[];wrong=[]
    for item in choices:
        key=item['key'];fact=facts.get(key)
        if (fact is not None and json.dumps(item.get('value'),sort_keys=True)==json.dumps(fact['value'],sort_keys=True)
                and set(fact['sources'])<=set(item.get('sources',[]))
                and not set(fact.get('obsolete_sources',[]))&set(item.get('sources',[]))):
            verified.append(key)
        else:wrong.append(key)
    return dict(total=len(facts),correct=len(verified),incorrect=len(wrong),omitted=len(set(facts)-set(keys)),
                citation_grounded_recall=len(verified)/len(facts),wrong_keys=wrong,
                note='Value and BOTH contract excerpt and approval must be found; no model judge')
